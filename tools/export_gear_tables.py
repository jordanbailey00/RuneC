#!/usr/bin/env python3
"""Compile RuneC's gear tables into C includes for rc-content/combat.

Inputs are RuneC-owned: content/items/gear.tsv and special_attacks.tsv.
gear_enums.inc names every family, flag, ammo kind and special; gear_rows.inc
is a designated-initializer table indexed by item ID.
"""
from __future__ import annotations

import argparse
from pathlib import Path

from content_paths import content_read_path

ROOT = Path(__file__).resolve().parents[1]
OUT_DIR = ROOT / "rc-content/combat"
BLOCK_OUT = ROOT / "rc-viewer/item_block_anims.inc"
HEADER = "// Generated by tools/export_gear_tables.py; edit content/items instead.\n"


def rows(path: Path) -> list[list[str]]:
    out = []
    for line in path.read_text().splitlines():
        if line and not line.startswith(("#", "item_id|")):
            out.append(line.split("|"))
    return out


def sym(prefix: str, value: str) -> str:
    return f"{prefix}{value.upper()}"


def generate(gear: list[list[str]], specials: list[list[str]]) -> tuple[str, str]:
    families = sorted({row[2] for row in gear} - {"-"})
    flags = sorted({flag for row in gear for flag in row[3].split(",")} - {"-"})
    kinds = sorted({row[4] for row in gear} - {"-"})
    handlers = sorted({row[3] for row in specials})
    if len(flags) > 32:
        raise ValueError("gear flags exceed the row's 32 bits")
    enums = [HEADER, "enum {\n    GEAR_NONE = 0,\n"]
    enums += [f"    {sym('GEAR_', name)},\n" for name in families]
    enums.append("    GEAR_FAMILY_COUNT,\n};\n\nenum {\n")
    enums += [f"    {sym('GEARF_', name)} = 1u << {i},\n" for i, name in enumerate(flags)]
    enums.append("};\n\nenum {\n    AMMO_NONE = 0,\n")
    enums += [f"    {sym('AMMO_', name)},\n" for name in kinds]
    enums.append("};\n\nenum {\n    SPECIAL_NONE = 0,\n")
    enums += [f"    {sym('SPECIAL_', name)},\n" for name in handlers]
    enums.append("    SPECIAL_COUNT,\n};\n")

    merged: dict[int, dict] = {}
    for row in gear:
        merged[int(row[0])] = {
            "family": sym("GEAR_", row[2]) if row[2] != "-" else "GEAR_NONE",
            "flags": " | ".join(sym("GEARF_", f) for f in row[3].split(",")) if row[3] != "-" else "0",
            "kind": sym("AMMO_", row[4]) if row[4] != "-" else "AMMO_NONE",
            "tier": int(row[5]),
        }
    blank = {"family": "GEAR_NONE", "flags": "0", "kind": "AMMO_NONE", "tier": 0}
    for row in specials:
        entry = merged.setdefault(int(row[0]), dict(blank))
        entry["cost"] = int(row[2])
        entry["special"] = sym("SPECIAL_", row[3])
        entry["variant"] = 1 if row[4] == "bh" else 0
    lines = [HEADER]
    for item_id in sorted(merged):
        e = merged[item_id]
        lines.append(
            f"[{item_id}] = {{{e['family']}, {e['flags']}, {e['kind']}, {e['tier']}, "
            f"{e.get('special', 'SPECIAL_NONE')}, {e.get('cost', 0)}, {e.get('variant', 0)}}},\n")
    return "".join(enums), "".join(lines)


def block_table(blocks: list[list[str]]) -> str:
    lines = [HEADER]
    for row in sorted(blocks, key=lambda r: int(r[0])):
        lines.append(f"{{{int(row[0])}, {int(row[2])}}},\n")
    return "".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="fail when the includes differ from the content tables")
    args = parser.parse_args()
    enums, table = generate(rows(content_read_path("items/gear.tsv")),
                            rows(content_read_path("items/special_attacks.tsv")))
    blocks = block_table(rows(content_read_path("items/block_anims.tsv")))
    for path, text in ((OUT_DIR / "gear_enums.inc", enums), (OUT_DIR / "gear_rows.inc", table),
                       (BLOCK_OUT, blocks)):
        if args.check:
            if not path.is_file() or path.read_text() != text:
                raise SystemExit(f"{path} is out of date; run tools/export_gear_tables.py")
        else:
            path.write_text(text)
    print(f"gear tables {'verified' if args.check else 'written'}: {OUT_DIR}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
